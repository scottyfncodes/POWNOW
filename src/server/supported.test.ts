import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { MOUNTAINS } from '@/data/mountains';
import { ORIGINS } from '@/data/origins';
import { mountainsInReach, resolveAccessRoutes } from '@/engine/routing';

/**
 * The server only spends Google calls on places the app can actually ask about.
 * `server/supported.mjs` is that list, generated from the app's own data: each
 * city's starting point and the mountain end points its ranking can request,
 * plus every mountain end point (an opened mountain is routed from a GPS fix to
 * the mountain itself, or along a city's authored route).
 *
 * When cities or mountains change, regenerate it:
 *   UPDATE_SUPPORTED=1 npx vitest run src/server/supported.test.ts
 */
const FILE = resolve(__dirname, '../../server/supported.mjs');
const key = (point: { lat: number; lon: number }) => `${point.lat.toFixed(4)},${point.lon.toFixed(4)}`;

function expected(): string {
  const cities: Record<string, { origin: string; destinations: string[] }> = {};
  const all = new Set<string>(MOUNTAINS.map((mountain) => key(mountain.coordinates)));
  for (const origin of ORIGINS) {
    const origins = new Set<string>();
    const destinations = new Set<string>();
    for (const mountain of mountainsInReach(MOUNTAINS, origin)) {
      for (const route of resolveAccessRoutes(mountain, origin)) {
        origins.add(key(route.originPoint));
        destinations.add(key(route.destinationPoint));
        all.add(key(route.destinationPoint));
      }
    }
    if (origins.size !== 1) throw new Error(`${origin.id}: expected one starting point, found ${origins.size}`);
    cities[origin.id] = { origin: [...origins][0] as string, destinations: [...destinations].sort() };
  }
  return [
    '// Generated by src/server/supported.test.ts from src/data. Do not edit by hand:',
    '//   UPDATE_SUPPORTED=1 npx vitest run src/server/supported.test.ts',
    '// Points are "lat,lon" at four decimals, the precision the client sends.',
    `export const SUPPORTED_CITIES = ${JSON.stringify(cities, null, 2)};`,
    `export const SUPPORTED_DESTINATIONS = ${JSON.stringify([...all].sort(), null, 2)};`,
    '',
  ].join('\n');
}

describe('server/supported.mjs', () => {
  it('matches the cities and mountains the app can ask about', () => {
    const want = expected();
    if (process.env.UPDATE_SUPPORTED) writeFileSync(FILE, want);
    expect(readFileSync(FILE, 'utf8')).toBe(want);
  });
});
